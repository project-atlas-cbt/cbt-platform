'use client';

import { ReactNode } from 'react';
import { useRouter } from 'next/navigation';
import { Printer, ArrowLeft, GraduationCap } from 'lucide-react';
import { Button } from '@/components/ui/button';
import { useTenant } from '@/lib/tenant';
import { useAuth } from '@/lib/auth';

export interface PrintLayoutProps {
  title: string;
  subtitle?: string;
  children: ReactNode;
}

export function PrintLayout({ title, subtitle, children }: PrintLayoutProps) {
  const router = useRouter();
  const { school } = useTenant();
  const { me } = useAuth();

  // P2-24: the school's own time, whatever the printing PC's clock says.
  const timeZone = school?.timezone ? { timeZone: school.timezone } : {};
  const generatedDate = new Date().toLocaleDateString('en-GB', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
    ...timeZone,
  });
  const generatedTime = new Date().toLocaleTimeString('en-GB', {
    hour: '2-digit',
    minute: '2-digit',
    ...timeZone,
  });

  return (
    <div className="min-h-screen bg-surface-muted/30 text-text-primary print:bg-white print:text-black">
      {/* Screen-Only Action Bar */}
      <header className="sticky top-0 z-10 flex items-center justify-between border-b border-border bg-surface px-6 py-3 shadow-sm print:hidden">
        <div className="flex items-center gap-3">
          <Button
            variant="secondary"
            size="sm"
            onClick={() => router.back()}
            className="gap-1.5"
            aria-label="Return to previous screen"
          >
            <ArrowLeft className="size-4" />
            <span>Back</span>
          </Button>
          <div>
            <h1 className="text-sm font-semibold text-text-primary">{title}</h1>
            {subtitle && <p className="text-xs text-text-muted">{subtitle}</p>}
          </div>
        </div>

        <div className="flex items-center gap-2">
          <Button
            variant="primary"
            size="sm"
            onClick={() => window.print()}
            className="gap-2"
            data-testid="print-button"
          >
            <Printer className="size-4" />
            <span>Print Report</span>
          </Button>
        </div>
      </header>

      {/* Printable Paper Canvas */}
      <main className="mx-auto max-w-5xl p-6 sm:p-10 print:p-0 print:max-w-none">
        <div className="rounded-lg border border-border bg-surface p-8 shadow-sm print:border-none print:shadow-none print:p-0">
          {/* Official Document Header */}
          <div className="border-b-2 border-black pb-4 mb-6">
            <div className="flex items-start justify-between gap-4">
              <div className="flex items-center gap-3.5">
                {school?.logoUrl ? (
                  <img
                    src={school.logoUrl}
                    alt={`${school.name} logo`}
                    className="size-14 object-contain"
                  />
                ) : (
                  <div className="flex size-14 items-center justify-center rounded bg-black text-white">
                    <GraduationCap className="size-8" aria-hidden />
                  </div>
                )}
                <div>
                  <h2 className="text-xl font-bold uppercase tracking-tight text-black">
                    {school?.name ?? 'School Examination Board'}
                  </h2>
                  <p className="text-xs text-black/70 uppercase tracking-wider font-medium">
                    Official Academic Assessment Record
                  </p>
                </div>
              </div>

              <div className="text-right text-xs text-black/80 space-y-0.5">
                <p className="font-semibold text-black">Date Generated:</p>
                <p>
                  {generatedDate} at {generatedTime}
                </p>
                {me && (
                  <p className="text-[11px] text-black/60">
                    Generated by: {me.user.displayName} ({me.membership.loginIdentifier})
                  </p>
                )}
              </div>
            </div>

            <div className="mt-5 text-center">
              <h3 className="text-lg font-bold uppercase tracking-wider text-black">{title}</h3>
              {subtitle && <p className="text-xs font-medium text-black/75 mt-0.5">{subtitle}</p>}
            </div>
          </div>

          {/* Document Content */}
          <div className="print-body">{children}</div>

          {/* Official Document Footer */}
          <div className="mt-12 pt-6 border-t border-black/30 text-xs text-black/70 print:break-inside-avoid">
            <div className="grid grid-cols-2 gap-8 mb-8 pt-4">
              <div>
                <div className="border-b border-black w-48 mb-1" />
                <p className="font-semibold">Examiner / Teacher Signature</p>
              </div>
              <div className="text-right flex flex-col items-end">
                <div className="border-b border-black w-48 mb-1" />
                <p className="font-semibold">Principal / Exam Officer Stamp</p>
              </div>
            </div>

            <div className="flex items-center justify-between text-[11px] text-black/60 border-t border-black/10 pt-3">
              {/* The school's document: its name, never the product's (Haneef, 2026-10-09). */}
              <span>{school?.name ?? ''}</span>
              <span>Official Academic Record</span>
            </div>
          </div>
        </div>
      </main>
    </div>
  );
}
